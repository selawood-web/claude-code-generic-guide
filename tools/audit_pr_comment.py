#!/usr/bin/env python3
"""Post (or update) one pull-request comment carrying an audit report.

The headless audit's only outward action. It writes nothing to the repository:
the report leaves as a workflow artifact and as this comment, which is replaced
in place on later runs rather than added to, so a pull request carries one audit
comment however many times the audit runs.

    python3 tools/audit_pr_comment.py --file CCGG-AUDIT-x/REPORT.md --repo owner/name --pr 12

Reads the token from GITHUB_TOKEN. Stdlib only — the workflow has no other
dependency to install, and a comment is not worth one.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request

MARKER = "<!-- ccgg-audit -->"
FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_"
# GitHub rejects a comment body over 65536 characters; leave room for the frame.
MAX_BODY = 60000
API = "https://api.github.com"


def comment_body(report: str, run_url: str | None = None, max_body: int = MAX_BODY) -> str:
    """The comment: the marker that identifies it, the report, and where the rest is."""
    if not isinstance(report, str):
        raise TypeError("report must be a string")
    text = report.strip() or "_The audit produced no report._"
    if len(text) > max_body:
        cut = text.rfind("\n", 0, max_body)
        text = text[: cut if cut > 0 else max_body].rstrip()
        text += "\n\n_Report truncated. The full report, the findings, and the assembled command are in this run's artifact._"
    tail = f"\n\n[Workflow run]({run_url})" if run_url else ""
    return f"{MARKER}\n{text}{tail}\n\n{FOOTER}\n"


def find_existing(comments: list, marker: str = MARKER) -> int | None:
    """The id of this workflow's own comment, or None. Anyone else's is left alone."""
    for comment in comments or []:
        if isinstance(comment, dict) and marker in str(comment.get("body") or ""):
            return comment.get("id")
    return None


def _call(url: str, token: str, method: str = "GET", payload: dict | None = None):
    data = json.dumps(payload).encode() if payload is not None else None
    request = urllib.request.Request(url, data=data, method=method)
    request.add_header("Authorization", f"Bearer {token}")
    request.add_header("Accept", "application/vnd.github+json")
    request.add_header("X-GitHub-Api-Version", "2022-11-28")
    if data is not None:
        request.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(request, timeout=30) as response:
        body = response.read().decode("utf-8", "replace")
    return json.loads(body) if body else None


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--file", required=True, help="the rendered REPORT.md")
    parser.add_argument("--repo", required=True, help="owner/name")
    parser.add_argument("--pr", required=True, type=int, help="pull request number")
    parser.add_argument("--run-url", default=None, help="link back to the workflow run")
    parser.add_argument("--dry-run", action="store_true", help="print the comment, post nothing")
    args = parser.parse_args(argv)

    try:
        with open(args.file, encoding="utf-8", errors="replace") as fh:
            report = fh.read()
    except OSError as exc:
        print(f"audit-pr-comment: {exc}", file=sys.stderr)
        return 1
    body = comment_body(report, args.run_url)
    if args.dry_run:
        print(body)
        return 0

    token = os.environ.get("GITHUB_TOKEN", "")
    if not token:
        print("audit-pr-comment: GITHUB_TOKEN is not set; nothing posted", file=sys.stderr)
        return 1
    base = f"{API}/repos/{args.repo}/issues/{args.pr}/comments"
    try:
        existing = _call(f"{base}?per_page=100", token)
        comment_id = find_existing(existing if isinstance(existing, list) else [])
        if comment_id:
            _call(f"{API}/repos/{args.repo}/issues/comments/{comment_id}", token, "PATCH", {"body": body})
            print(f"audit-pr-comment: updated comment {comment_id}")
        else:
            _call(base, token, "POST", {"body": body})
            print("audit-pr-comment: posted a new comment")
    except (urllib.error.URLError, json.JSONDecodeError, OSError) as exc:
        print(f"audit-pr-comment: could not post the comment: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
