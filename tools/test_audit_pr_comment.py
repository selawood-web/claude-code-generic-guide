#!/usr/bin/env python3
"""Unit tests for audit_pr_comment.py — the audit's only outward action.

The HTTP call itself is not tested; everything that decides what gets said, and
which comment gets replaced, is.

Run: python -m unittest discover -s tools -p "test_*.py"
"""

import io
import os
import tempfile
import unittest
from contextlib import redirect_stdout

import audit_pr_comment
from audit_pr_comment import MARKER, comment_body, find_existing


class CommentBodyTests(unittest.TestCase):
    def test_carries_the_marker_report_and_footer(self):
        body = comment_body("# CCGG audit report\n\n2 findings.")
        self.assertTrue(body.startswith(MARKER))
        self.assertIn("2 findings.", body)
        self.assertIn("_Generated by [Claude Code](https://claude.ai/code)_", body)

    def test_run_url_is_linked_when_given(self):
        self.assertIn("[Workflow run](https://x/run/1)", comment_body("r", "https://x/run/1"))
        self.assertNotIn("Workflow run", comment_body("r"))

    def test_empty_report_says_so_rather_than_posting_nothing(self):
        self.assertIn("no report", comment_body("   "))

    def test_long_report_is_truncated_at_a_line_break_and_says_where_the_rest_is(self):
        report = "\n".join(f"line {n}" for n in range(5000))
        body = comment_body(report, max_body=500)
        self.assertLess(len(body), 1200)
        self.assertIn("Report truncated", body)
        self.assertNotIn("line 4999", body)
        self.assertTrue(body.rstrip().endswith("_Generated by [Claude Code](https://claude.ai/code)_"))

    def test_truncation_without_a_line_break_still_cuts(self):
        self.assertIn("Report truncated", comment_body("x" * 2000, max_body=100))

    def test_non_string_raises(self):
        with self.assertRaises(TypeError):
            comment_body(None)


class FindExistingTests(unittest.TestCase):
    def test_finds_our_own_comment(self):
        comments = [{"id": 1, "body": "unrelated"}, {"id": 2, "body": f"{MARKER}\nold report"}]
        self.assertEqual(find_existing(comments), 2)

    def test_leaves_other_comments_alone(self):
        self.assertIsNone(find_existing([{"id": 1, "body": "a human's review"}]))

    def test_tolerates_empty_and_malformed_entries(self):
        self.assertIsNone(find_existing([]))
        self.assertIsNone(find_existing(None))
        self.assertIsNone(find_existing([{"id": 1}, "not a dict", {"body": None}]))


class MainTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="ccgg-comment-")
        self.report = os.path.join(self.tmp.name, "REPORT.md")
        with open(self.report, "w", encoding="utf-8") as fh:
            fh.write("# CCGG audit report\n\n1 finding.\n")

    def tearDown(self):
        self.tmp.cleanup()

    def test_dry_run_prints_and_posts_nothing(self):
        out = io.StringIO()
        with redirect_stdout(out):
            code = audit_pr_comment.main(["--file", self.report, "--repo", "o/r", "--pr", "1", "--dry-run"])
        self.assertEqual(code, 0)
        self.assertIn(MARKER, out.getvalue())

    def test_missing_file_is_an_error(self):
        code = audit_pr_comment.main(["--file", "/nonexistent/REPORT.md", "--repo", "o/r", "--pr", "1", "--dry-run"])
        self.assertEqual(code, 1)

    def test_no_token_posts_nothing(self):
        before = os.environ.pop("GITHUB_TOKEN", None)
        try:
            code = audit_pr_comment.main(["--file", self.report, "--repo", "o/r", "--pr", "1"])
        finally:
            if before is not None:
                os.environ["GITHUB_TOKEN"] = before
        self.assertEqual(code, 1)


if __name__ == "__main__":
    unittest.main()
